import { Icon, type IconProps } from "@iconify/react";

function createSolarIcon(name: string) {
  function SolarIcon(props: Omit<IconProps, "icon">) {
    return <Icon icon={`solar:${name}-linear`} {...props} />;
  }

  SolarIcon.displayName = name;
  return SolarIcon;
}

